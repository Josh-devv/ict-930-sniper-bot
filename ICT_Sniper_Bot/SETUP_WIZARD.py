def ask(prompt, default=""):
    val = input(f"  {prompt}: ").strip()
    return val if val else default

email    = ask("Your Tradovate email")
password = ask("Your Tradovate password")
cid      = ask("Your API CID (number from Tradovate API page)")
secret   = ask("Your API Secret (from Tradovate API page)")
symbol   = ask("NQ Contract symbol (press Enter for NQZ4)", "NQZ4")
contracts= ask("Number of contracts to trade (1 recommended)", "1")
live     = ask("Live trading? Type YES to trade real money (default: NO)", "NO")

device_id = str(uuid.uuid4())

env_content = f"""# ICT Sniper Bot — Configuration
# Generated by Setup Wizard

TRADOVATE_USER={email}
TRADOVATE_PASS={password}
TRADOVATE_APP_ID=ICT_Sniper_Bot
TRADOVATE_APP_VERSION=1.0
TRADOVATE_DEVICE_ID={device_id}
TRADOVATE_CID={cid}
TRADOVATE_SECRET={secret}
NQ_SYMBOL={symbol}
CONTRACTS={contracts}
LIVE_MODE={"true" if live.upper() == "YES" else "false"}
"""

with open(".env", "w") as f:
    f.write(env_content)

print()
print("=" * 55)
print("  Configuration saved to .env")
print(f"  Symbol   : {symbol}")
print(f"  Contracts: {contracts}")
print(f"  Mode     : {'*** LIVE ***' if live.upper() == 'YES' else 'DEMO (paper trading)'}")
